-- Admin panel: two-step sign-in and the SEO manager. Additive, safe to run twice. Re-run after a load-db --force.

ALTER TABLE admin_users ADD COLUMN IF NOT EXISTS login_attempts integer NOT NULL DEFAULT 0;
ALTER TABLE admin_users ADD COLUMN IF NOT EXISTS locked_until timestamp DEFAULT NULL;

CREATE TABLE IF NOT EXISTS admin_login_otps (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL,
  code_hash   varchar(64) NOT NULL,
  ip_address  varchar(64) DEFAULT NULL,
  attempts    integer NOT NULL DEFAULT 0,
  expires_at  timestamp NOT NULL,
  consumed_at timestamp DEFAULT NULL,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS admin_login_otps_user ON admin_login_otps (user_id, created_at);

CREATE TABLE IF NOT EXISTS admin_login_failures (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_address varchar(64) NOT NULL,
  username   varchar(100) DEFAULT NULL,
  created_at timestamp NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS admin_login_failures_ip ON admin_login_failures (ip_address, created_at);

-- One SEO record per public URL. Anything not set here falls back to the URL's own defaults.
CREATE TABLE IF NOT EXISTS seo_meta (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type   varchar(20)  NOT NULL CHECK (entity_type IN ('page', 'product', 'category')),
  entity_key    varchar(200) NOT NULL,
  title         varchar(200) DEFAULT NULL,
  description   varchar(400) DEFAULT NULL,
  focus_keyword varchar(120) DEFAULT NULL,
  og_image      varchar(500) DEFAULT NULL,
  canonical_url varchar(500) DEFAULT NULL,
  noindex       smallint NOT NULL DEFAULT 0,
  schema_json   text DEFAULT NULL,
  updated_at    timestamp NOT NULL DEFAULT LOCALTIMESTAMP,
  UNIQUE (entity_type, entity_key)
);

ALTER TABLE seo_redirects ADD COLUMN IF NOT EXISTS last_hit_at timestamp DEFAULT NULL;
ALTER TABLE seo_redirects ADD COLUMN IF NOT EXISTS note varchar(255) DEFAULT NULL;
