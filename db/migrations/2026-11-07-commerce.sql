-- Order tracking, back-in-stock alerts and abandoned-bag reminders. Additive, safe to run twice. Re-run after a load-db --force.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS courier_name varchar(100) DEFAULT NULL;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tracking_number varchar(100) DEFAULT NULL;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tracking_url varchar(500) DEFAULT NULL;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipped_at timestamp DEFAULT NULL;

-- One row per product and email; notified_at is set when the "back in stock" email goes out.
CREATE TABLE IF NOT EXISTS stock_alerts (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  email       varchar(254) NOT NULL,
  customer_id integer DEFAULT NULL,
  ip_address  varchar(64) DEFAULT NULL,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP,
  notified_at timestamp DEFAULT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS stock_alerts_product_email ON stock_alerts (product_id, lower(email));
CREATE INDEX IF NOT EXISTS stock_alerts_waiting ON stock_alerts (product_id) WHERE notified_at IS NULL;

-- When a customer was last reminded about items left in their bag, so nobody gets more than one a week.
CREATE TABLE IF NOT EXISTS cart_reminders (
  customer_id integer PRIMARY KEY,
  sent_at     timestamp NOT NULL DEFAULT LOCALTIMESTAMP
);
